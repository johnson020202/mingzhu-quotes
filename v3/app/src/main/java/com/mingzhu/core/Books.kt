    /** 今天该读哪本书：以固定纪元日为序，按书数循环。 */
    fun bookForDay(dayIndex: Long): Book {
        val i = ((dayIndex % books.size) + books.size) % books.size
        return books[i.toInt()]
    }

    fun byId(id: String): Book? = books.firstOrNull { it.id == id }
